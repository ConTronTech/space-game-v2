const std::vector<Stroke>& glyphStrokes(char c) {
    static const std::vector<Stroke> none;
    auto it = table().find((char)std::toupper((unsigned char)c));
    return it == table().end() ? none : it->second;
}

bool hasGlyph(char c) { return !glyphStrokes(c).empty(); }

float textAdvance(float height) { return height * kCellAspect * (1.0f + kGapRatio); }

float textWidth(const std::string& text, float height) {
    if (text.empty()) return 0;
    return textAdvance(height) * (float)(text.size() - 1) + height * kCellAspect;
}

void layoutText(const std::string& text, float x, float y, float height, std::vector<Stroke>& out) {
    float cw = height * kCellAspect, adv = textAdvance(height);
    float cx = x;
    for (char c : text) {
        for (const Stroke& s : glyphStrokes(c))
            out.push_back({cx + s.x1 * cw, y + s.y1 * height, cx + s.x2 * cw, y + s.y2 * height});
        cx += adv;
    }
}

